function titleCase(value: string): string {
  const smallWords = new Set(['and', 'for', 'with']);
  return value
    .toLowerCase()
    .split(' ')
    .filter(Boolean)
    .map((word, index) =>
      index > 0 && smallWords.has(word) ? word : `${word.charAt(0).toUpperCase()}${word.slice(1)}`,
    )
    .join(' ');
}

