export function productModelGroup(sku: string): 'LA' | 'F' | 'RA' | 'ACA' | undefined {
  const prefix = sku.split('-')[0]?.toUpperCase();
  return prefix === 'LA' || prefix === 'F' || prefix === 'RA' || prefix === 'ACA'
    ? prefix
    : undefined;
}
